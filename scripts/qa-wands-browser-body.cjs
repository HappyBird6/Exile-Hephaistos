;(async () => {
  browser = await chromium.launch({ headless: true })
  page = await (await browser.newContext({ viewport: { width: 1440, height: 1100 } })).newPage()
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://host.docker.internal:20181', { waitUntil: 'networkidle' })
  for (const [base,b] of Object.entries(bases).filter(([,b]) => b.family === 'wands')) {
    await locale('en')
    await place(base)
    check(base + ' exact selector identity', active(await history()).frames[0].state.baseItemId === b.id)
    check(base + ' Wand class', await page.locator('.bench-item-card .item-card__class').innerText() === 'Wands')
    const r = await use('Orb_of_Transmutation', true)
    check(base + ' positive Transmutation', r.applied)
    check(base + ' Shift selection retained',await page.getByRole('button',{name:terms.en.Orb_of_Transmutation.name,exact:true}).getAttribute('aria-pressed') === 'true')
    await seed({...concrete(initials[base]),rarity:'MAGIC'},base+'-sorcery')
    await locale('en')
    check(base + ' positive Essence',(await use('Greater_Essence_of_Sorcery')).applied)
    const d = Object.values(initials[base].modifiers).find(d=>d.weight > 0 && d.stats.length > 1 && d.stats.some(s=>s.min !== s.max))
    check(base+' compound display fixture exists',Boolean(d))
    await seed({...concrete(initials[base]),rarity:'RARE',explicits:[{modifierId:d.id,values:Object.fromEntries(d.stats.map(s=>[s.id,s.min])),fractured:true}]},base+'-compound')
    for (const l of locales) {
      await locale(l)
      let card = await page.locator('.bench-item-card').innerText()
      check(base + ' '+l+' localized name',card.includes(terms[l][b.slug].name))
      for (const line of b.sourceProperties[l]) check(base+' '+l+' granted skill',card.includes(line))
      check(base+' '+l+' canonical requirements',card.replace(/\s+/g,' ').includes(b.requirements[l].replace(/\s+/g,' ')))
      const saved = await raw()
      for (const width of [1440,390]) {
        await page.setViewportSize({width,height:1100})
        check(base+' '+l+' '+width+' no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth))
        await page.screenshot({path:`/evidence/${base}-${l}-${width}.png`,fullPage:true})
        await page.locator('.bench-item-card').screenshot({path:`/evidence/cards/${base}-${l}-${width}.png`})
        await page.keyboard.down('Alt')
        await page.waitForFunction(text=>document.querySelector('.bench-item-card').innerText !== text,card)
        check(base+' Alt ranges displayed',await page.locator('.bench-item-card').innerText() !== card)
        check(base+' Alt preserves film',await raw() === saved)
        await page.keyboard.up('Alt')
      }
    }
  }
  await page.setViewportSize({width:1440,height:1100})
  await locale('en')
  const orangeDefinition = Object.values(initials.dueling.modifiers).find(d=>d.weight > 0 && d.stats.length > 1)
  await seed({...concrete(initials.dueling),rarity:'RARE',explicits:[{modifierId:orangeDefinition.id,values:Object.fromEntries(orangeDefinition.stats.map(s=>[s.id,s.min])),fractured:false}]},'dueling-preview')
  const previewBefore=await raw()
  await page.locator('#tab-Omen').click()
  await page.getByRole('button',{name:terms.en.Omen_of_Whittling.name,exact:true}).click()
  const favorite=page.locator('.favorite-slot').first()
  await favorite.click()
  await favorite.click({button:'right'})
  await page.waitForSelector('.bench-item-card .item-card__line--removal-candidate')
  for(const l of locales){
    await locale(l)
    check(l+' local orange preview',await page.locator('.item-card__line--removal-candidate').evaluate(el=>getComputedStyle(el).color) === 'rgb(255, 166, 77)')
    check(l+' preview preserves film',await raw() === previewBefore)
    await page.screenshot({path:`/evidence/dueling-orange-${l}.png`,fullPage:true})
  }
  await favorite.click({button:'right'})
  await locale('en')
  const films = Object.entries(oldInitials).map(([id,i])=>({id:'old-'+id,createdAt:'2026-10-04T00:00:00Z',frames:[{state:concrete(i),action:null}]}))
  for (const film of films) {
    await page.evaluate(({key,films,id})=>localStorage.setItem(key,JSON.stringify({version:1,films,active:id,cursor:0})),{key,films,id:film.id})
    await page.reload({waitUntil:'networkidle'})
    await page.waitForSelector('.bench-item-card')
    check(film.id+' old film restores',active(await history()).id === film.id)
    check(film.id+' old film state exact',JSON.stringify(active(await history()).frames[0].state) === JSON.stringify(film.frames[0].state))
  }
  const life = Object.values(initials.solar.modifiers).find(d=>d.familyIds.includes('IncreasedLife') && d.requiredItemLevel === 1 && d.stats.length === 1)
  const lifeStat = life.stats[0], originalLife = lifeStat.min + 1
  check('source life rounding fixture inside range',originalLife <= lifeStat.max)
  await seed({...concrete(initials.solar),rarity:'RARE',catalystQuality:{type:'FLESH',amount:40},explicits:[{modifierId:life.id,values:{[lifeStat.id]:originalLife},fractured:false}]},'solar-overflow')
  const repeated = await use('Flesh_Catalyst')
  check('Solar overflow quality40 and cap20 preserved',repeated.applied && repeated.state.catalystQuality.amount === 40 && repeated.qualityLimit.maximumQuality === 20)
  for(const l of locales){
    await locale(l)
    const stored=active(await history()).frames.at(-1).state
    check(l+' Solar original roll retained',stored.explicits[0].values[lifeStat.id] === originalLife)
    check(l+' HALF_UP retained',(await page.locator('.bench-item-card .item-card__line--explicit').innerText()).includes(String(Math.round(originalLife*140/100))))
    await page.screenshot({path:`/evidence/solar-overflow-${l}.png`,fullPage:true})
  }
  check('browser page errors absent',errors.length === 0)
  fs.writeFileSync('/evidence/browser-results.json',JSON.stringify({passed:true,count:checks.length,checks,errors},null,2)+'\n')
  console.log(checks.length,'browser checks passed')
  await browser.close()
})().catch(async e=>{console.error(e);if(browser)await browser.close();process.exit(1)})

// Generated artifacts contain no independent policy. --check is read-only; --write is explicit.
import fs from "node:fs";
import assert from "node:assert/strict";
import {
  root,
  readJSON,
  localeContract,
  localeCodes,
  repeatContract,
} from "./public-contracts.mjs";
const write = process.argv.includes("--write");
function emit(path, text) {
  if (write) fs.writeFileSync(root + path, text);
  else
    assert.equal(
      fs.readFileSync(root + path, "utf8"),
      text,
      `Generated contract drift: ${path}; run node scripts/sync-public-contracts.mjs --write`,
    );
}
const clean = Object.fromEntries(
  Object.entries(repeatContract).filter(([k]) => !k.startsWith("_")),
);
assert(
  clean.minimumUses <= clean.defaultUses &&
    clean.defaultUses <= clean.maximumUses,
);
assert(Object.values(clean).every((n) => Number.isSafeInteger(n) && n > 0));
assert(localeCodes.includes(localeContract.defaultLocale));
const generated =
  "// Generated by scripts/sync-public-contracts.mjs; edit backend/src/main/resources/contracts instead.\n";
emit(
  "frontend/src/shared/contracts/public.ts",
  generated +
    `// prettier-ignore
export const repeatContract = ${JSON.stringify(clean)} as const\n// prettier-ignore\nexport const localeContract = ${JSON.stringify(localeContract)} as const\n// prettier-ignore\nexport const locales = ${JSON.stringify(localeCodes)} as const\n`,
);
emit(
  "infra/docker/chaos-repeat-limits.conf",
  `# Generated from contracts/chaos-repeat.json; do not edit.\nclient_max_body_size ${clean.maximumBodyBytes};\n`,
);
const schema = readJSON("contracts/workbench-definitions-v1.schema.json");
const defs = readJSON(
  "backend/src/main/resources/crafting/workbench-definitions-v1.json",
);
for (const [key, id] of [
  ["currencies", "id"],
  ["omens", "key"],
]) {
  const property = schema.properties[key];
  property.minItems = property.maxItems = defs[key].length;
  property.items.properties[id].enum = defs[key].map((row) => row[id]);
}
emit(
  "contracts/workbench-definitions-v1.schema.json",
  JSON.stringify(schema, null, 2) + "\n",
);
console.log("Public contracts verified");
const bases = readJSON("backend/src/main/resources/catalog/top-bases.json");
const legacy = readJSON(
  "backend/src/main/resources/catalog/base-policies.json",
).legacy;
const augments = readJSON("backend/src/main/resources/catalog/augments.json");
const policy = readJSON(
  "backend/src/main/resources/crafting/automatic-currency-policy-v1.json",
);
const table = [
  "| 항목 | 현행 값 |",
  "|---|---|",
  `| 등록 베이스 | ${new Set([...Object.keys(bases), ...Object.keys(legacy)]).size} |`,
  `| UI 언어 | ${localeCodes.join(", ")} (기본 ${localeContract.defaultLocale}) |`,
  `| 증강물 | 등록 ${augments.length} / 선택 ${augments.filter((row) => row.selectionEnabled).length} |`,
  `| 화폐·징조 실행 정의 | ${defs.currencies.length} / ${defs.omens.length} (보관함 표시 정책과 별개) |`,
  `| 카오스 반복 | 기본 ${clean.defaultUses}, 범위 ${clean.minimumUses}–${clean.maximumUses} |`,
  `| 반복 요청 본문 | ${clean.maximumBodyBytes} UTF-8 bytes |`,
  `| 패턴 | 길이 ${clean.patternLength}, 깊이 ${clean.patternDepth}, 문법 노드 ${clean.patternNodes}, 프로그램 ${clean.patternProgram} |`,
  `| 제작지원 정책 | ${policy.policyVersion} |`,
].join("\n");
const document = "docs/current/support.md",
  content = fs.readFileSync(root + document, "utf8");
const marker =
  /<!-- generated:public-contracts:start -->[\s\S]*?<!-- generated:public-contracts:end -->/;
assert(marker.test(content), "Missing generated summary marker");
emit(
  document,
  content.replace(
    marker,
    "<!-- generated:public-contracts:start -->\n" +
      table +
      "\n<!-- generated:public-contracts:end -->",
  ),
);
const goalSchema = readJSON("contracts/goal-definitions-v1.schema.json");
const goal = readJSON(
  "backend/src/main/resources/crafting/goalfilter/definitions-v1.json",
);
for (const stat of goal.stats)
  for (const field of Object.keys(stat))
    assert(
      field in goalSchema.properties.stats.items.properties,
      `Goal contract does not recognize ${field}`,
    );

from playwright.sync_api import sync_playwright,expect
import json
results=[]
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page();page.on('pageerror',lambda e:print('PAGEERROR',e))
 page.goto('http://127.0.0.1:5177/review-browser.html')
 page.get_by_role('button',name='Select this item state').click()
 page.get_by_text('Rare-result endings',exact=True).first.click()
 expect(page.get_by_role('checkbox',name='Rare-result endings')).not_to_be_checked()
 results.append('restored disabled despite enabled preference and missing flow')
 for i in range(1,4):
  page.locator('fieldset select').nth(i-1).select_option('p')
 for field in page.locator('fieldset input[type=number]').all():field.fill('17')
 page.get_by_role('button',name='Reveal / replace observed candidates').click()
 page.get_by_role('button',name='Choose',exact=True).first.click()
 page.get_by_role('button',name='Continue crafting search from this item').click()
 page.wait_for_function('window.review.requests.length === 1')
 req=page.evaluate('window.review.requests[0]')
 assert req[0]['clientRequestId']!='synthetic:create-1' and req[4]['enabled']==False
 assert req[0]['start']['item']['explicits'][0]['values']['life']==17
 results.append('observed life 17 entered, chosen, continued with new ID and disabled policy')
 page.get_by_text('Rare-result endings',exact=True).first.click()
 page.get_by_role('checkbox',name='Rare-result endings').check()
 page.get_by_role('button',name='Start new calculation with these settings').click()
 page.wait_for_function('window.review.requests.length === 2')
 assert page.evaluate('window.review.requests[1][4].enabled')
 results.append('explicit enabled change preserved in new request')
 page.goto('http://127.0.0.1:5177/review-browser.html?mode=cancel')
 page.get_by_text('Rare-result endings',exact=True).first.click()
 page.get_by_role('checkbox',name='Rare-result endings').check()
 page.evaluate("window.review.fail=true;window.review.view.status='READY'")
 page.get_by_role('button',name='Start new calculation with these settings').click()
 expect(page.get_by_role('alert')).to_contain_text('Could not confirm cancellation')
 assert page.evaluate('window.review.requests.length')==0
 page.evaluate('window.review.fail=false')
 page.get_by_role('button',name='Start new calculation with these settings').click()
 page.wait_for_function('window.review.requests.length === 1')
 results.append('cancellation network failure keeps old screen, explicit retry creates new session')
 page.goto('http://127.0.0.1:5177/review-browser.html?mode=late')
 page.get_by_role('button',name='Select this item state').click()
 page.get_by_role('button',name='Continue calculation').click()
 page.wait_for_function('!!window.review.finish')
 page.get_by_role('button',name='Continue crafting search from this item').click()
 page.wait_for_function('window.review.requests.length === 1')
 page.evaluate("window.review.finish({...window.review.view,revision:999,generation:999,rareOutcomePolicy:{...window.review.view.rareOutcomePolicy,enabled:true}})")
 page.wait_for_timeout(200)
 page.get_by_text('Rare-result endings',exact=True).first.click()
 expect(page.get_by_role('checkbox',name='Rare-result endings')).not_to_be_checked()
 assert page.evaluate('window.review.requests.length')==1
 results.append('late old resume response does not overwrite new session policy')
 page.screenshot(path='/tmp/policy-browser-success.png',full_page=True)
 print(json.dumps(results,indent=2));open('/tmp/policy-browser-results.json','w').write(json.dumps(results,indent=2))
 b.close()
